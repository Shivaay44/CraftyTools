// --- Helper Functions & Build-Time Registry Assertions ---

export function getAllTools(): ToolDefinition[] {
  return TOOLS;
}

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: ToolCategory): ToolDefinition[] {
  return TOOLS.filter((t) => t.category === category);
}

export function getRelatedTools(tool: ToolDefinition): ToolDefinition[] {
  return tool.relatedTools
    .map((slug) => getToolBySlug(slug))
    .filter((t): t is ToolDefinition => t !== undefined);
}

// Build-time validation assertion function to ensure strict data integrity
export function validateToolRegistry(): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  const slugs = new Set<string>();

  if (TOOLS.length === 0) {
    errors.push('No tools found in registry.');
  }

  for (const tool of TOOLS) {
    if (slugs.has(tool.slug)) {
      errors.push(`Duplicate tool slug found: "${tool.slug}".`);
    }
    slugs.add(tool.slug);
  }

  for (const tool of TOOLS) {
    for (const relatedSlug of tool.relatedTools) {
      if (!slugs.has(relatedSlug)) {
        errors.push(`Tool "${tool.slug}" references invalid relatedTool slug: "${relatedSlug}".`);
      }
    }
  }

  return { valid: errors.length === 0, errors };
}

// Execute self-check assertion immediately on module load
const validationResult = validateToolRegistry();
if (!validationResult.valid) {
  console.error('[Tool Registry Error]', validationResult.errors.join(' | '));
}
